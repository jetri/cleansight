import { expect, test } from '@playwright/test';
import { installMockHttp } from './fixture';
import { uuid } from '../data';

test('polling preserves player/focus and feedback failures/corrections preserve drafts and machine history', async ({ page }, info) => {
  const state = await installMockHttp(page, info.outputPath('synthetic-media'));
  const machine = JSON.stringify({ outcome: state.events[0]!.machine_outcome, transitions: state.events[0]!.transitions });
  await page.goto('/ui-assets/');
  const pane = page.getByRole('tabpanel', { name: 'Evidence desk', exact: true });
  await pane.getByLabel('Phase filter', { exact: true }).selectOption('final');
  const video = pane.locator('video');
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.readyState)).toBeGreaterThanOrEqual(1);
  await video.evaluate(async (element: HTMLVideoElement) => { await element.play(); });
  const original = await video.elementHandle();
  const review = pane.getByRole('region', { name: 'Separate human feedback', exact: true });
  await review.getByLabel('Ambiguous / cannot judge', { exact: true }).check();
  await review.getByLabel('Local reviewer label', { exact: true }).fill('browser-fixture-reviewer');
  const notes = review.getByLabel('Review notes', { exact: true });
  await notes.fill('Synthetic fixture: cannot determine physical contact.');
  const reads = state.calls.filter(call => call.path === `/api/events/${uuid(6)}`).length;
  await expect.poll(() => state.calls.filter(call => call.path === `/api/events/${uuid(6)}`).length).toBeGreaterThan(reads);
  await expect(notes).toBeFocused();
  await expect(notes).toHaveValue('Synthetic fixture: cannot determine physical contact.');
  expect(await original!.evaluate(element => element.isConnected)).toBe(true);
  expect(await video.evaluate((element: HTMLVideoElement) => element.paused)).toBe(false);
  await video.evaluate((element: HTMLVideoElement) => element.pause());
  state.failReviewOnce = true;
  await review.getByRole('button', { name: 'Save feedback', exact: true }).click();
  await expect(review.getByText(/Injected definite validation failure/)).toBeVisible();
  await expect(notes).toHaveValue('Synthetic fixture: cannot determine physical contact.');
  let release!: () => void;
  state.reviewResponseWait = new Promise<void>(resolve => { release = resolve; });
  await review.getByRole('button', { name: 'Retry feedback save', exact: true }).click();
  await expect(review.getByRole('button', { name: 'Saving…', exact: true })).toBeVisible();
  await notes.fill('Newer retained draft: source remains ambiguous; no physical conclusion.');
  release();
  await expect(review.getByText(/Newer edits are still unsaved/)).toBeVisible();
  await expect(notes).toHaveValue('Newer retained draft: source remains ambiguous; no physical conclusion.');
  state.reviewResponseWait = null;
  await review.getByRole('button', { name: 'Save feedback correction', exact: true }).click();
  await expect(review.getByText('Server acknowledged', { exact: true })).toBeVisible();
  expect(state.events[0]!.reviews).toHaveLength(2);
  expect(state.events[0]!.reviews[1]!.supersedes_id).toBe(state.events[0]!.reviews[0]!.id);
  expect(state.events[0]!.reviews[0]!.notes).toBe('Synthetic fixture: cannot determine physical contact.');
  expect(JSON.stringify({ outcome: state.events[0]!.machine_outcome, transitions: state.events[0]!.transitions })).toBe(machine);
  await page.reload();
  await expect(review.getByLabel('Review notes', { exact: true })).toHaveValue('Newer retained draft: source remains ambiguous; no physical conclusion.');
  await review.getByText('Stored feedback history / 2 record(s)', { exact: true }).click();
  await expect(review.getByText('Synthetic fixture: cannot determine physical contact.', { exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('feedback-readback-history.png') });
  expect(state.unhandled).toEqual([]);
});

