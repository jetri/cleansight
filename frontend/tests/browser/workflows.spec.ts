test('lost replay acknowledgement discovers a new identity and inspects actual indexed source frames', async ({ page }, info) => {
  const state = await installMockHttp(page, info.outputPath('synthetic-media'));
  state.loseReplayAcknowledgement = true;
  await page.goto('/ui-assets/');
  await page.getByRole('tab', { name: 'Capture & replay', exact: true }).click();
  const pane = page.getByRole('tabpanel', { name: 'Capture & replay', exact: true });
  await pane.getByRole('button', { name: 'Create replay run', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Create local replay run', exact: true });
  await dialog.getByLabel('Captured source session', { exact: true }).selectOption(uuid(3));
  await dialog.getByRole('button', { name: 'Create new run', exact: true }).click();
  await expect(dialog.getByText('Run acknowledgement unknown / no retry sent', { exact: true })).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Create new run', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: /Inspect discovered run/ }).click();
  const created = state.runs.find(run => run.id !== uuid(5))!;
  await expect(pane.getByLabel('Selected run', { exact: true })).toHaveValue(created.id);
  expect(created.session_id).toBe(uuid(3));
  expect(created.configuration_id).toBe(uuid(2));
  expect(state.calls.filter(call => call.method === 'POST' && call.path.endsWith('/replays'))).toHaveLength(1);
  const frames = pane.getByRole('region', { name: 'Source-indexed frame inspection', exact: true });
  await frames.getByRole('button', { name: 'Inspect first indexed frame', exact: true }).click();
  const image = frames.getByAltText('Unredacted source-indexed evidence frame', { exact: true });
  const resolved = frames.locator('.evidence-footer .facts > div').filter({ hasText: 'Resolved source' });
  await expect(resolved).toContainText('+0.000s');
  await expect.poll(() => image.evaluate((element: HTMLImageElement) => element.naturalWidth)).toBe(320);
  await frames.getByRole('button', { name: 'Next indexed frame', exact: true }).click();
  await expect(resolved).toContainText('+0.100s');
  await expect.poll(() => image.evaluate((element: HTMLImageElement) => element.naturalWidth)).toBe(320);
  const requests = state.calls.filter(call => call.method === 'POST' && call.path.endsWith('/frames'));
  expect(requests.map(call => call.body)).toEqual([{ source_us: 0 }, { source_us: 100_000 }]);
  await page.screenshot({ path: info.outputPath('replay-indexed-frame.png') });
  await page.reload();
  await expect(pane.getByLabel('Selected run', { exact: true })).toHaveValue(created.id);
  expect(state.unhandled).toEqual([]);
});

test('source start, reconnect and stop keep desired acknowledgements separate from observed sessions', async ({ page }, info) => {
  const state = await installMockHttp(page, info.outputPath('synthetic-media'));
  await page.goto('/ui-assets/');
  await page.getByRole('tab', { name: 'Sources & zones', exact: true }).click();
  const pane = page.getByRole('tabpanel', { name: 'Sources & zones', exact: true });
  await pane.getByRole('button', { name: 'Start recording', exact: true }).click();
  await expect(pane.getByText(/Start requested and stored/)).toBeVisible();
  await expect(pane.getByRole('button', { name: 'Reconnect', exact: true })).toBeEnabled();
  const first = state.sessions.find(session => !session.stopped_at)!;
  await pane.getByRole('button', { name: 'Reconnect', exact: true }).click();
  await expect.poll(() => state.sessions.filter(session => !session.stopped_at).map(session => session.id)).not.toEqual([first.id]);
  await expect(pane.getByText(/Start requested and stored/)).toBeVisible();
  expect(state.sessions.find(session => session.id === first.id)!.stopped_at).not.toBeNull();
  expect(state.sessions.filter(session => !session.stopped_at)).toHaveLength(1);
  await pane.getByRole('button', { name: 'Stop recording', exact: true }).click();
  await expect(pane.getByText(/Stop requested and stored/)).toBeVisible();
  expect(state.sessions.filter(session => !session.stopped_at)).toHaveLength(0);
  expect(state.calls.filter(call => call.method === 'POST' && call.path.endsWith('/recording')).map(call => call.body)).toEqual([{ enabled: true }, { enabled: false }, { enabled: true }, { enabled: false }]);
  expect(state.unhandled).toEqual([]);
});
