import { expect, test } from '@playwright/test';
import { installMockHttp } from './fixture';
import { uuid } from '../data';

test('separate recorded parts follow ordered coverage and never auto-cross the contextual gap', async ({ page }, info) => {
  const state = await installMockHttp(page, info.outputPath('synthetic-media'));
  await page.goto('/ui-assets/');
  const pane = page.getByRole('tabpanel', { name: 'Evidence desk', exact: true });
  await pane.getByRole('button', { name: new RegExp(state.events[1]!.id.slice(0, 8)) }).click();
  const playback = pane.getByRole('region', { name: 'Evidence clip playback', exact: true });
  const parts = pane.getByLabel('Chronological recorded part / never auto-cross gaps', { exact: true });
  await expect(parts).toHaveValue(uuid(18));
  expect(state.events[1]!.clips[0]!.media[0]).toBe(uuid(88));
  const video = playback.locator('video');
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.duration)).toBeCloseTo(6, 1);
  await expect(video).toHaveAttribute('src', `/media/${uuid(18)}`);
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.readyState)).toBeGreaterThanOrEqual(3);
  console.log('Native multipart seek readiness', await video.evaluate((element: HTMLVideoElement) => ({ duration: element.duration, readyState: element.readyState, seekable: Array.from({ length: element.seekable.length }, (_, index) => [element.seekable.start(index), element.seekable.end(index)]) })));
  await video.evaluate((element: HTMLVideoElement) => { element.currentTime = 5.7; });
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => !element.seeking && element.currentTime >= 5.6)).toBe(true);
  await video.evaluate(async (element: HTMLVideoElement) => { await element.play(); });
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.ended)).toBe(true);
  await expect(parts).toHaveValue(uuid(18));
  await expect(video).toHaveAttribute('src', `/media/${uuid(18)}`);
  await parts.selectOption(uuid(88));
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.duration)).toBeCloseTo(1, 1);
  await expect(video).toHaveAttribute('src', `/media/${uuid(88)}`);
  await expect(playback.locator('.evidence-footer')).toContainText('+7.000s');
  expect(await video.evaluate((element: HTMLVideoElement) => element.paused)).toBe(true);
  await video.evaluate((element: HTMLVideoElement) => { element.currentTime = .2; });
  await expect(playback.locator('.evidence-footer')).toContainText('+7.200s');
  await pane.getByRole('button', { name: new RegExp(state.events[0]!.id.slice(0, 8)) }).click();
  await pane.getByRole('button', { name: new RegExp(state.events[1]!.id.slice(0, 8)) }).click();
  await expect(parts).toHaveValue(uuid(88));
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.currentTime)).toBeCloseTo(.2, 2);
  await page.screenshot({ path: info.outputPath('manual-second-part-after-gap.png') });
  expect(state.unhandled).toEqual([]);
});

test('native media failure stays unavailable and an explicit read reload can recover actual playback', async ({ page }, info) => {
  const state = await installMockHttp(page, info.outputPath('synthetic-media'));
  state.unavailableMedia = true;
  const pageErrors: string[] = [];
  page.on('pageerror', error => pageErrors.push(error.message));
  await page.goto('/ui-assets/');
  const playback = page.getByRole('region', { name: 'Evidence clip playback', exact: true });
  await expect(playback.getByText(/The media is missing, expired, unreadable or unsupported/)).toBeVisible();
  await page.screenshot({ path: info.outputPath('native-media-unavailable.png') });
  state.unavailableMedia = false;
  await playback.getByRole('button', { name: 'Reload video / retain position', exact: true }).click();
  const video = playback.locator('video');
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.readyState)).toBeGreaterThanOrEqual(1);
  await video.evaluate(async (element: HTMLVideoElement) => { await element.play(); });
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.currentTime)).toBeGreaterThan(.2);
  await video.evaluate((element: HTMLVideoElement) => element.pause());
  await expect(playback.getByText(/The media is missing, expired, unreadable or unsupported/)).toHaveCount(0);
  expect(state.calls.filter(call => call.method === 'POST')).toHaveLength(0);
  expect(pageErrors).toEqual([]);
  expect(state.unhandled).toEqual([]);
});

test('bounded media reservation validates input and is read back independently from playback', async ({ page }, info) => {
  const state = await installMockHttp(page, info.outputPath('synthetic-media'));
  await page.goto('/ui-assets/');
  const provenance = page.getByLabel('Media provenance and bounded reservations', { exact: true });
  await provenance.getByText('Media provenance, storage & reservations', { exact: true }).click();
  const duration = provenance.getByLabel('Reservation duration (seconds)', { exact: true });
  await duration.fill('0');
  const reserve = provenance.getByRole('button', { name: 'Reserve current media', exact: true });
  await expect(reserve).toBeDisabled();
  await duration.fill('120');
  await reserve.click();
  await expect(provenance.getByText(/Reservation .* was stored until/)).toBeVisible();
  const active = provenance.locator('.facts > div').filter({ hasText: 'Active reservations' });
  await expect(active).toContainText('1');
  expect(state.calls.filter(call => call.method === 'POST' && call.path.endsWith('/pins')).map(call => call.body)).toEqual([{ purpose: 'local-evidence-inspection', seconds: 120 }]);
  await page.reload();
  await provenance.getByText('Media provenance, storage & reservations', { exact: true }).click();
  await expect(active).toContainText('1');
  await page.screenshot({ path: info.outputPath('bounded-reservation-readback.png') });
  expect(state.unhandled).toEqual([]);
});
